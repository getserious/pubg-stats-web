"""PostgreSQL adapter for GAME.GG community tables only.

PUBG cache/telemetry remains on the original SQLite database.
"""
import os
import re
import threading
from contextlib import contextmanager

import psycopg
from psycopg.rows import dict_row

_init_lock = threading.Lock()
_initialized = False


class BoardRow(dict):
    """Support existing sqlite3.Row access: row['field'] and row[0]."""
    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values())[key]
        return super().__getitem__(key)


def _row_factory(cursor):
    if cursor.description is None:
        return lambda row: row

    names = [col.name for col in cursor.description]

    def make_row(row):
        return dict(zip(names, row))

    return make_row


class BoardCursor:
    def __init__(self, cursor, lastrowid=None):
        self._cursor = cursor
        self.lastrowid = lastrowid
        self.rowcount = cursor.rowcount

    def fetchone(self):
        return self._cursor.fetchone()

    def fetchall(self):
        return self._cursor.fetchall()


class BoardConnection:
    def __init__(self, conn):
        self._conn = conn

    def execute(self, sql, params=None):
        statement = sql.strip()
        if statement.upper() == 'BEGIN IMMEDIATE':
            # psycopg already starts a transaction on the first SQL command.
            return BoardCursor(self._conn.cursor())
        # The community SQL uses '?' placeholders, not literal '?' operators.
        statement = statement.replace('?', '%s')
        inserting = bool(re.match(r'^INSERT\s+INTO\s+community_(users|posts|comments)\b', statement, re.I))
        if inserting and 'RETURNING' not in statement.upper():
            statement += ' RETURNING id'
        cursor = self._conn.execute(statement, params or ())
        inserted_id = None
        if inserting:
            inserted = cursor.fetchone()
            inserted_id = inserted['id'] if inserted else None
        return BoardCursor(cursor, inserted_id)

    def commit(self):
        self._conn.commit()

    def __enter__(self):
        self._conn.__enter__()
        return self

    def __exit__(self, exc_type, exc, tb):
        return self._conn.__exit__(exc_type, exc, tb)


def _initialize(conn):
    global _initialized
    if _initialized:
        return
    with _init_lock:
        if _initialized:
            return
        # Multiple Gunicorn workers may initialize concurrently.
        conn.execute('SELECT pg_advisory_xact_lock(72201956)')
        conn.execute('''CREATE TABLE IF NOT EXISTS community_users (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            login_id TEXT NOT NULL,
            display_name TEXT NOT NULL,
            password_hash TEXT NOT NULL,
            created_at BIGINT NOT NULL)''')
        conn.execute('CREATE UNIQUE INDEX IF NOT EXISTS idx_community_users_login_lower ON community_users (lower(login_id))')
        conn.execute('''CREATE TABLE IF NOT EXISTS community_posts (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            category TEXT NOT NULL, nickname TEXT NOT NULL, platform TEXT NOT NULL,
            title TEXT NOT NULL, body TEXT NOT NULL, min_rp INTEGER, mode TEXT,
            created_at BIGINT NOT NULL, author_user_id BIGINT,
            completed INTEGER NOT NULL DEFAULT 0, expires_at BIGINT,
            completed_at BIGINT, completion_reason TEXT,
            matched_comment_id BIGINT, matched_nickname TEXT)''')
        # Also allow older PostgreSQL community_posts schemas to be upgraded.
        for name, typ in (
            ('author_user_id','BIGINT'), ('completed','INTEGER NOT NULL DEFAULT 0'),
            ('expires_at','BIGINT'), ('completed_at','BIGINT'),
            ('completion_reason','TEXT'), ('matched_comment_id','BIGINT'),
            ('matched_nickname','TEXT')):
            conn.execute(f'ALTER TABLE community_posts ADD COLUMN IF NOT EXISTS {name} {typ}')
        conn.execute('''CREATE TABLE IF NOT EXISTS community_comments (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            post_id BIGINT NOT NULL, user_id BIGINT,
            nickname TEXT NOT NULL, body TEXT NOT NULL, created_at BIGINT NOT NULL)''')
        conn.execute('CREATE INDEX IF NOT EXISTS idx_comments_post ON community_comments(post_id,id)')
        conn.execute('''CREATE TABLE IF NOT EXISTS community_auth_attempts (
            key TEXT PRIMARY KEY, failures INTEGER NOT NULL DEFAULT 0,
            window_start BIGINT NOT NULL)''')
        conn.commit()
        _initialized = True


def board_conn():
    url = os.environ.get('DATABASE_URL', '').strip()
    if not url:
        raise RuntimeError('DATABASE_URL is missing; community PostgreSQL is not configured')
    conn = psycopg.connect(url, row_factory=_row_factory, connect_timeout=10)
    try:
        _initialize(conn)
        # Commit lifecycle updates before returning to match existing board_conn().
        conn.execute("UPDATE community_posts SET expires_at=created_at+%s WHERE category IN ('duo','squad') AND expires_at IS NULL", (1800,))
        import time
        now = int(time.time())
        conn.execute("UPDATE community_posts SET completed=1,completed_at=expires_at,completion_reason='expired' WHERE category IN ('duo','squad') AND completed=0 AND expires_at<=%s", (now,))
        conn.commit()
        return BoardConnection(conn)
    except Exception:
        conn.close()
        raise
